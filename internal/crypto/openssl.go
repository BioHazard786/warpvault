package crypto

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"

	"golang.org/x/crypto/pbkdf2"
)

const (
	// OpenSSLMagic is the standard 8-byte prefix prepended by `openssl enc`.
	OpenSSLMagic = "Salted__"

	// SaltLen is the standard 8-byte salt size used by OpenSSL PBKDF2.
	SaltLen = 8

	// KeyLen is the AES-256 key size in bytes.
	KeyLen = 32

	// IVLen is the AES block/IV size in bytes.
	IVLen = aes.BlockSize // 16 bytes

	// PBKDF2Iterations matches the default iteration count of OpenSSL 3.x.
	PBKDF2Iterations = 10000

	// DerivedMaterialLen is KeyLen + IVLen (48 bytes).
	DerivedMaterialLen = KeyLen + IVLen
)

var (
	ErrInvalidHeader   = errors.New("invalid openssl header: missing Salted__ magic")
	ErrPayloadTooShort = errors.New("encrypted payload is too short")
	ErrInvalidPadding  = errors.New("invalid PKCS#7 padding: corrupted ciphertext or wrong passphrase")
	ErrEmptyPassphrase = errors.New("passphrase cannot be empty")
)

// DeriveKeyAndIV computes the 32-byte AES key and 16-byte CBC IV from the passphrase and salt
// using PBKDF2 with HMAC-SHA256, matching OpenSSL's internal derivation algorithm.
func DeriveKeyAndIV(passphrase []byte, salt []byte) (key []byte, iv []byte) {
	derived := pbkdf2.Key(passphrase, salt, PBKDF2Iterations, DerivedMaterialLen, sha256.New)
	return derived[:KeyLen], derived[KeyLen:DerivedMaterialLen]
}

// Encrypt encrypts the plaintext with AES-256-CBC using OpenSSL's standard PBKDF2 container format.
// The output is 100% interoperable with:
// `openssl enc -d -aes-256-cbc -pbkdf2 -pass pass:<passphrase>`
func Encrypt(plaintext []byte, passphrase string) ([]byte, error) {
	if passphrase == "" {
		return nil, ErrEmptyPassphrase
	}

	salt := make([]byte, SaltLen)
	if _, err := io.ReadFull(rand.Reader, salt); err != nil {
		return nil, fmt.Errorf("failed to generate random salt: %w", err)
	}

	key, iv := DeriveKeyAndIV([]byte(passphrase), salt)

	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("failed to create AES cipher: %w", err)
	}

	padded := pkcs7Pad(plaintext, aes.BlockSize)
	ciphertext := make([]byte, len(padded))

	mode := cipher.NewCBCEncrypter(block, iv)
	mode.CryptBlocks(ciphertext, padded)

	// Construct OpenSSL wire format: "Salted__" (8 bytes) + Salt (8 bytes) + Ciphertext
	out := make([]byte, len(OpenSSLMagic)+SaltLen+len(ciphertext))
	copy(out[0:8], OpenSSLMagic)
	copy(out[8:16], salt)
	copy(out[16:], ciphertext)

	return out, nil
}

// Decrypt decrypts an OpenSSL PBKDF2-AES-CBC container payload.
// It accepts ciphertext generated by `openssl enc -aes-256-cbc -pbkdf2` or Web Crypto API.
func Decrypt(data []byte, passphrase string) ([]byte, error) {
	if passphrase == "" {
		return nil, ErrEmptyPassphrase
	}

	minLen := len(OpenSSLMagic) + SaltLen + aes.BlockSize
	if len(data) < minLen {
		return nil, ErrPayloadTooShort
	}

	if string(data[:8]) != OpenSSLMagic {
		return nil, ErrInvalidHeader
	}

	salt := data[8:16]
	ciphertext := data[16:]

	if len(ciphertext)%aes.BlockSize != 0 {
		return nil, errors.New("ciphertext length is not a multiple of AES block size")
	}

	key, iv := DeriveKeyAndIV([]byte(passphrase), salt)

	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("failed to create AES cipher: %w", err)
	}

	plaintext := make([]byte, len(ciphertext))
	mode := cipher.NewCBCDecrypter(block, iv)
	mode.CryptBlocks(plaintext, ciphertext)

	unpadded, err := pkcs7Unpad(plaintext)
	if err != nil {
		return nil, ErrInvalidPadding
	}

	return unpadded, nil
}

// GenerateRandomKey generates a cryptographically secure 16-byte random key formatted
// as a 32-character hexadecimal string, ideal for URL fragments and passphrases.
func GenerateRandomKey() (string, error) {
	bytes := make([]byte, 16)
	if _, err := io.ReadFull(rand.Reader, bytes); err != nil {
		return "", err
	}
	return hex.EncodeToString(bytes), nil
}

// pkcs7Pad appends PKCS#7 padding to align the buffer to the given block size.
func pkcs7Pad(data []byte, blockSize int) []byte {
	padding := blockSize - (len(data) % blockSize)
	padText := bytes.Repeat([]byte{byte(padding)}, padding)
	return append(data, padText...)
}

// pkcs7Unpad validates and removes PKCS#7 padding from the buffer.
func pkcs7Unpad(data []byte) ([]byte, error) {
	length := len(data)
	if length == 0 || length%aes.BlockSize != 0 {
		return nil, errors.New("invalid data length for unpadding")
	}

	padding := int(data[length-1])
	if padding == 0 || padding > aes.BlockSize || padding > length {
		return nil, ErrInvalidPadding
	}

	for i := length - padding; i < length; i++ {
		if data[i] != byte(padding) {
			return nil, ErrInvalidPadding
		}
	}

	return data[:length-padding], nil
}
