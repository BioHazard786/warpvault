// Regenerates protocol/fixtures/vectors.json. Run from web/: bun scripts/gen-fixtures.mjs
// Vectors come from node:crypto, independent of the WebCrypto and Go code that must match them.
import { createCipheriv, hkdfSync, pbkdf2Sync } from "node:crypto"
import { mkdirSync, writeFileSync } from "node:fs"

const out = new URL("../../protocol/fixtures/", import.meta.url)
mkdirSync(out, { recursive: true })

const hex = (b) => Buffer.from(b).toString("hex")
const fill = (n, start) => Buffer.from(Array.from({ length: n }, (_, i) => (start + i * 7) & 0xff))
const PBKDF2_ITERATIONS = 600_000

function seal({ kind, name, data, passphrase }, k, salt, nonce) {
  const nameBytes = Buffer.from(name, "utf8")
  const lenBuf = Buffer.alloc(2)
  lenBuf.writeUInt16BE(nameBytes.length)
  const plaintext = Buffer.concat([Buffer.from([kind]), lenBuf, nameBytes, data])

  const flags = passphrase === null ? 0 : 1
  let ikm = k
  let info = "warpvault/1"
  if (passphrase !== null) {
    ikm = Buffer.concat([
      k,
      pbkdf2Sync(Buffer.from(passphrase, "utf8"), salt, PBKDF2_ITERATIONS, 32, "sha256"),
    ])
    info = "warpvault/1/pass"
  }
  const key = Buffer.from(hkdfSync("sha256", ikm, salt, info, 32))

  const header = Buffer.concat([Buffer.from([1, flags]), salt, nonce])
  const c = createCipheriv("aes-256-gcm", key, nonce)
  c.setAAD(header)
  const ct = Buffer.concat([c.update(plaintext), c.final(), c.getAuthTag()])
  return { key: hex(key), blob: hex(Buffer.concat([header, ct])) }
}

const cases = [
  {
    name: "text, random key only",
    kind: 0,
    fname: "",
    data: Buffer.from("sk_live_999888777"),
    passphrase: null,
  },
  { name: "text, single byte", kind: 0, fname: "", data: Buffer.from("x"), passphrase: null },
  {
    name: "file, random key only",
    kind: 1,
    fname: "id_ed25519.pem",
    data: fill(300, 3),
    passphrase: null,
  },
  {
    name: "text, with passphrase",
    kind: 0,
    fname: "",
    data: Buffer.from("line 1\nline 2 ünïcödé ✓\n"),
    passphrase: "correct horse",
  },
  {
    name: "file, unicode name, with passphrase",
    kind: 1,
    fname: "séc✓ret.env",
    data: fill(64, 200),
    passphrase: "pä55 w0rd ✓",
  },
]

const vectors = cases.map((c, i) => {
  const k = fill(32, 10 + i)
  const salt = fill(16, 40 + i)
  const nonce = fill(12, 90 + i)
  const { key, blob } = seal(
    { kind: c.kind, name: c.fname, data: c.data, passphrase: c.passphrase },
    k,
    salt,
    nonce,
  )
  return {
    name: c.name,
    k: hex(k),
    kBase64url: k.toString("base64url"),
    salt: hex(salt),
    nonce: hex(nonce),
    passphrase: c.passphrase,
    kind: c.kind,
    filename: c.fname,
    data: hex(c.data),
    derivedKey: key,
    blob,
  }
})

writeFileSync(
  new URL("vectors.json", out),
  JSON.stringify(
    { note: "generated by web/scripts/gen-fixtures.mjs; all byte values hex", vectors },
    null,
    2,
  ) + "\n",
)
console.log(`wrote ${vectors.length} vectors`)
