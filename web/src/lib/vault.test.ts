import { readFileSync } from "node:fs"
import { describe, expect, test } from "vitest"
import {
  b64urlDecode,
  newKey,
  needsPassphrase,
  open,
  seal,
  sealedSize,
  VaultError,
  type Secret,
} from "./vault"

type Vector = {
  name: string
  kBase64url: string
  salt: string
  nonce: string
  passphrase: string | null
  kind: number
  filename: string
  data: string
  blob: string
}

const hex = (h: string) => new Uint8Array(h.match(/../g)?.map((b) => parseInt(b, 16)) ?? [])
const toHex = (b: Uint8Array) => [...b].map((x) => x.toString(16).padStart(2, "0")).join("")
const vectors: Vector[] = JSON.parse(
  readFileSync(new URL("../../../protocol/fixtures/vectors.json", import.meta.url), "utf8"),
).vectors

describe("protocol fixtures (generated by node:crypto)", () => {
  test.each(vectors)("$name", async (v) => {
    const secret: Secret = {
      kind: v.kind === 1 ? "file" : "text",
      name: v.filename,
      data: hex(v.data),
    }
    const pass = v.passphrase ?? ""
    const sealed = await seal(secret, v.kBase64url, pass, {
      salt: hex(v.salt),
      nonce: hex(v.nonce),
    })
    expect(toHex(sealed)).toBe(v.blob)
    expect(sealed.length).toBe(sealedSize(secret))
    expect(needsPassphrase(sealed)).toBe(v.passphrase !== null)

    const opened = await open(hex(v.blob), v.kBase64url, pass)
    expect(opened.kind).toBe(secret.kind)
    expect(opened.name).toBe(secret.name)
    expect(toHex(opened.data)).toBe(v.data)
  })
})

describe("seal/open", () => {
  test("round trip with a random key, with and without passphrase", async () => {
    const key = newKey()
    expect(key).toHaveLength(43)
    expect(b64urlDecode(key)?.length).toBe(32)
    for (const pass of ["", "hunter2"]) {
      const blob = await seal(
        { kind: "text", name: "", data: new TextEncoder().encode("hi ✓") },
        key,
        pass,
      )
      const out = await open(blob, key, pass)
      expect(new TextDecoder().decode(out.data)).toBe("hi ✓")
    }
  })

  test("wrong key, wrong passphrase, missing passphrase and any flipped byte all fail", async () => {
    const key = newKey()
    const blob = await seal({ kind: "text", name: "", data: new Uint8Array([1, 2, 3]) }, key, "pw")
    await expect(open(blob, key, "")).rejects.toMatchObject({ code: "passphrase-required" })
    await expect(open(blob, key, "nope")).rejects.toMatchObject({ code: "decrypt" })
    await expect(open(blob, newKey(), "pw")).rejects.toMatchObject({ code: "decrypt" })
    await expect(open(blob, "not a key", "pw")).rejects.toMatchObject({ code: "bad-key" })

    const plain = await seal({ kind: "text", name: "", data: new Uint8Array([1, 2, 3]) }, key)
    for (let i = 0; i < plain.length; i++) {
      const bad = plain.slice()
      bad[i]! ^= 1
      await expect(open(bad, key)).rejects.toBeInstanceOf(VaultError)
    }
    await expect(open(new Uint8Array(10), key)).rejects.toMatchObject({ code: "not-blob" })
  })
})
